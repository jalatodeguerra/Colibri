//! Host functions that a coroutine calls run on pooled native stacks, and park there when they
//! wait for a background operation (vm-plan §3.2): the call completes when the coroutine is
//! resumed, the stacks are reused, and a function marked `no_await` never needs one.

use std::cell::RefCell;
use std::io::Write;
use std::rc::Rc;
use std::sync::Arc;
use std::sync::atomic::{AtomicBool, AtomicUsize, Ordering};
use std::time::{Duration, Instant};

use colibri_check::HostEnv;
use colibri_check::hir::HostFnId;
use colibri_check::host::{body_hash, header_line};
use colibri_core::external::ExternalError;
use colibri_core::release::Release;
use colibri_core::value::Value;
use colibri_syntax::{FileId, parse_file};
use colibri_vm::{HostFault, HostImpl, Machine, VmFiber};

#[derive(Clone, Default)]
struct Out(Rc<RefCell<Vec<u8>>>);

impl Write for Out {
    fn write(&mut self, buf: &[u8]) -> std::io::Result<usize> {
        self.0.borrow_mut().extend_from_slice(buf);
        Ok(buf.len())
    }
    fn flush(&mut self) -> std::io::Result<()> {
        Ok(())
    }
}

impl Out {
    fn text(&self) -> String {
        String::from_utf8_lossy(&self.0.borrow()).into_owned()
    }
}

/// The host functions of every test here, in this order (their ids): `nap` waits for a
/// background operation, `quick` never waits, `call_back` runs a Colibri function from the
/// host function, `pause_for_cancel` waits until it is cancelled.
const HOST: &str = "fn nap(n: int) -> int\nfn quick() -> int\nfn call_back(f: fn())\nfn pause_for_cancel()\nfn dive(n: int)\n";
const NAP: HostFnId = HostFnId(0);
const QUICK: HostFnId = HostFnId(1);
const CALL_BACK: HostFnId = HostFnId(2);
const PAUSE: HostFnId = HostFnId(3);
const DIVE: HostFnId = HostFnId(4);

fn int(v: &Value) -> i64 {
    match v {
        Value::Int(n) => *n,
        other => panic!("not an int: {other:?}"),
    }
}

fn load(src: &str, max_depth: usize) -> (Machine, colibri_check::Program, Out) {
    let text = format!(
        "// Generated by colibri-runtime; do not edit.\n{}\n{HOST}",
        header_line("host", &body_hash(HOST), &[])
    );
    let env = HostEnv::from_text(&text).expect("the interface parses");
    let (ast, diags) = parse_file(FileId(0), src);
    assert!(diags.is_empty(), "{diags:?}");
    let checked = colibri_check::check_with_host(&ast, &env, 1 << 20);
    let program = checked
        .program
        .unwrap_or_else(|| panic!("{:?}", checked.diagnostics));
    let out = Out::default();
    let mut m = Machine::new(Box::new(out.clone()), max_depth);
    m.set_native_stack_budget(64 << 20);
    m.load(&program);
    (m, program, out)
}

/// `nap(n)`: waits on a pool thread, then gives `n * 10`.
fn nap_impl() -> HostImpl {
    Rc::new(
        |m: &mut Machine, f: &mut VmFiber, args: Vec<Value>| -> Result<Value, HostFault> {
            let n = int(&args[0]);
            m.await_external(f, move || n * 10)
                .map(Value::Int)
                .map_err(|e| match e {
                    ExternalError::Cancelled => HostFault::Cancel,
                    other => HostFault::Message(format!("{other:?}")),
                })
        },
    )
}

fn quick_impl() -> HostImpl {
    Rc::new(|_: &mut Machine, _: &mut VmFiber, _: Vec<Value>| Ok(Value::Int(7)))
}

fn run_main(m: &mut Machine, p: &colibri_check::Program) -> Result<Value, String> {
    let mut fiber = VmFiber::new();
    m.call(&mut fiber, p.fn_by_name("main").expect("main"), vec![])
        .map_err(|e| e.message)
}

/// Two coroutines wait in `nap` at the same moment: the work of each starts before either ends
/// (a coroutine that blocked the thread in `nap` would keep the other from starting its work), and
/// each call then completes with its own result in the coroutine that made it.
#[test]
fn two_coroutines_wait_in_host_functions_at_once_and_each_gets_its_result() {
    let src = "fn worker(n: int) -> int {\n    let v = nap(n)\n    return v + 1\n}\nfn main() {\n    let a = go worker(1)\n    let b = go worker(2)\n    print(\"started\")\n    print(\"{a.join()} {b.join()}\")\n}\n";
    let (mut m, p, out) = load(src, 200);
    let inflight = Arc::new(AtomicUsize::new(0));
    let both = Arc::new(AtomicBool::new(true));
    let (i, b) = (Arc::clone(&inflight), Arc::clone(&both));
    m.set_host_fn(
        NAP,
        Rc::new(
            move |m: &mut Machine, f: &mut VmFiber, args: Vec<Value>| -> Result<Value, HostFault> {
                let n = int(&args[0]);
                let (i, b) = (Arc::clone(&i), Arc::clone(&b));
                let r = m.await_external(f, move || {
                    i.fetch_add(1, Ordering::SeqCst);
                    let start = Instant::now();
                    while i.load(Ordering::SeqCst) < 2 {
                        if start.elapsed() > Duration::from_secs(20) {
                            b.store(false, Ordering::SeqCst);
                            break;
                        }
                        std::thread::sleep(Duration::from_millis(1));
                    }
                    n * 10
                });
                r.map(Value::Int).map_err(|_| HostFault::Cancel)
            },
        ),
    );
    run_main(&mut m, &p).expect("main");
    assert!(both.load(Ordering::SeqCst), "the two operations overlapped");
    assert_eq!(out.text(), "started\n11 21\n");
    assert_eq!(m.coroutine_slots_live(), 0);
}

/// Serial waits reuse one stack: a thousand parks map one stack from the system, and it goes back
/// to the pool each time.
#[test]
fn a_thousand_waits_one_after_the_other_use_one_stack() {
    let src = "fn worker() -> int {\n    let mut sum = 0\n    for i in 0..1000 {\n        sum = sum + nap(i)\n    }\n    return sum\n}\nfn main() {\n    let c = go worker()\n    print(\"{c.join()}\")\n}\n";
    let (mut m, p, out) = load(src, 200);
    m.set_host_fn(NAP, nap_impl());
    run_main(&mut m, &p).expect("main");
    assert_eq!(out.text(), format!("{}\n", 10 * (0..1000).sum::<i64>()));
    assert_eq!(m.host_stacks_allocated(), 1, "one stack, mapped once");
    assert_eq!(m.host_stacks_pooled(), 1, "and back in the pool");
}

/// A function marked `no_await` runs on the caller's stack, one that is not marked on a stack of its
/// own, and the main fiber's calls never need one.
#[test]
fn only_a_function_that_may_wait_gets_a_stack_and_only_in_a_coroutine() {
    let src = "fn worker() -> int {\n    let mut sum = 0\n    for _ in 0..100 {\n        sum = sum + quick()\n    }\n    return sum\n}\nfn main() {\n    let m = quick()\n    let c = go worker()\n    print(\"{m} {c.join()}\")\n}\n";
    let (mut m, p, out) = load(src, 200);
    m.set_host_fn(QUICK, quick_impl());
    m.set_host_no_await(QUICK);
    run_main(&mut m, &p).expect("main");
    assert_eq!(out.text(), "7 700\n");
    assert_eq!(
        m.host_stacks_allocated(),
        0,
        "a marked function needs no stack"
    );

    // The same function, not marked: each call from the coroutine runs on a stack (one,
    // reused), the call from the main fiber on none.
    let (mut m, p, out) = load(src, 200);
    m.set_host_fn(QUICK, quick_impl());
    run_main(&mut m, &p).expect("main");
    assert_eq!(out.text(), "7 700\n");
    assert_eq!(m.host_stacks_allocated(), 1);

    let only_main = "fn main() {\n    print(\"{quick()}\")\n}\n";
    let (mut m, p, out) = load(only_main, 200);
    m.set_host_fn(QUICK, quick_impl());
    run_main(&mut m, &p).expect("main");
    assert_eq!(out.text(), "7\n");
    assert_eq!(
        m.host_stacks_allocated(),
        0,
        "the main fiber calls on its own stack"
    );
}

/// A coroutine that is cancelled while it is parked in a host function: the function's wait ends with
/// `Cancelled` after the token's hooks have run (they run before `cancel` returns), the function
/// unwinds, the coroutine's `defer` runs and it ends cancelled, and its stack goes back to the pool.
#[test]
fn cancelling_a_coroutine_parked_in_a_host_function_runs_the_hooks_and_ends_the_function() {
    let src = "fn worker() {\n    defer print(\"defer ran\")\n    pause_for_cancel()\n    print(\"not reached\")\n}\nfn main() {\n    let c = go worker()\n    wait(0.01)\n    c.cancel()\n    print(\"cancelled {c.done()}\")\n}\n";
    let (mut m, p, out) = load(src, 200);
    let hook = Arc::new(AtomicBool::new(false));
    let saw_cancel = Rc::new(RefCell::new(None));
    let (h, s) = (Arc::clone(&hook), Rc::clone(&saw_cancel));
    m.set_host_fn(
        PAUSE,
        Rc::new(
            move |m: &mut Machine, f: &mut VmFiber, _: Vec<Value>| -> Result<Value, HostFault> {
                let h = Arc::clone(&h);
                let r = m.await_external_with(f, move |token| {
                    let h2 = Arc::clone(&h);
                    token.on_cancel(move || h2.store(true, Ordering::SeqCst));
                    let start = Instant::now();
                    while !token.is_cancelled() && start.elapsed() < Duration::from_secs(30) {
                        std::thread::sleep(Duration::from_millis(1));
                    }
                });
                *s.borrow_mut() = Some(matches!(r, Err(ExternalError::Cancelled)));
                r.map(|()| Value::Unit).map_err(|_| HostFault::Cancel)
            },
        ),
    );
    run_main(&mut m, &p).expect("main");
    assert_eq!(
        *saw_cancel.borrow(),
        Some(true),
        "the wait ended with Cancelled"
    );
    assert!(hook.load(Ordering::SeqCst), "the token's hook ran");
    assert_eq!(out.text(), "defer ran\ncancelled true\n");
    assert_eq!(m.coroutine_slots_live(), 0);
    assert_eq!(
        m.host_stacks_pooled(),
        1,
        "the stack of the cancelled call was recycled"
    );
}

/// A host function on a stack may call back into Colibri, which may start a coroutine that waits in a
/// host function of its own, on a second stack run from inside the first: both complete, and the
/// parked callback's coroutine is not disturbed.
#[test]
fn a_callback_may_start_coroutines_that_wait_in_host_functions_too() {
    let src = "fn child() {\n    let v = nap(5)\n    print(\"child {v}\")\n}\nfn callback() {\n    let c = go child()\n    print(\"callback started child\")\n}\nfn parent() {\n    call_back(callback)\n    let v = nap(1)\n    print(\"parent {v}\")\n}\nfn main() {\n    let p = go parent()\n    p.join()\n    wait(0.2)\n    print(\"main end\")\n}\n";
    let (mut m, p, out) = load(src, 200);
    m.set_host_fn(NAP, nap_impl());
    m.set_host_fn(
        CALL_BACK,
        Rc::new(
            |m: &mut Machine, f: &mut VmFiber, args: Vec<Value>| -> Result<Value, HostFault> {
                match m.call_function(f, &args[0], vec![]) {
                    Ok(v) => {
                        m.release(v);
                        m.release(args.into_iter().next().unwrap());
                        Ok(Value::Unit)
                    }
                    Err(e) => Err(HostFault::Message(e.message)),
                }
            },
        ),
    );
    run_main(&mut m, &p).expect("main");
    assert_eq!(
        out.text(),
        "callback started child\nparent 10\nchild 50\nmain end\n"
    );
    assert_eq!(m.coroutine_slots_live(), 0);
}

/// The native recursion of callbacks on a host stack is measured against that stack, not the stack the
/// dispatch loop runs on: a host function that calls back into Colibri code that calls the host
/// function again stops with a clean panic, long before the 256 KiB of the stack are gone.
#[test]
fn recursion_through_host_callbacks_on_a_host_stack_ends_in_a_clean_panic() {
    let src = "fn again(n: int) {\n    dive(n + 1)\n}\nfn worker() {\n    dive(0)\n}\nfn main() {\n    let c = go worker()\n    let r = c.join_result()\n    print(\"{r.is_err()}\")\n}\n";
    let (mut m, p, out) = load(src, 1_000_000);
    // The budget a test sets for the dispatch loop's own stack is not the one a host stack gets.
    m.set_native_stack_budget(1 << 40);
    let again = p.fn_by_name("again").expect("again");
    m.set_host_fn(
        DIVE,
        Rc::new(
            move |m: &mut Machine, f: &mut VmFiber, args: Vec<Value>| -> Result<Value, HostFault> {
                match m.call(f, again, vec![args[0].clone()]) {
                    Ok(v) => {
                        m.release(v);
                        Ok(Value::Unit)
                    }
                    Err(e) => Err(HostFault::Message(e.message)),
                }
            },
        ),
    );
    run_main(&mut m, &p).expect("main");
    assert_eq!(out.text(), "true\n");
}

/// A machine that is dropped while a coroutine is parked in a host function cancels it: the wait
/// ends with `Cancelled` and the function returns, so its stack is run to its end and not dropped
/// suspended. The machine is boxed: a parked stack holds references into it, so it must not move
/// (moving it is caught when the stack is resumed, and ends the process).
#[test]
fn a_machine_dropped_with_a_parked_host_function_cancels_it() {
    let src = "fn worker() {\n    defer print(\"defer ran\")\n    pause_for_cancel()\n}\nfn main() {\n    let _c = go worker()\n}\n";
    let (m, p, out) = load(src, 200);
    let mut m = Box::new(m);
    let cancelled = Rc::new(RefCell::new(false));
    let c = Rc::clone(&cancelled);
    m.set_host_fn(
        PAUSE,
        Rc::new(
            move |m: &mut Machine, f: &mut VmFiber, _: Vec<Value>| -> Result<Value, HostFault> {
                let r = m.await_external_with(f, move |token| {
                    let start = Instant::now();
                    while !token.is_cancelled() && start.elapsed() < Duration::from_secs(30) {
                        std::thread::sleep(Duration::from_millis(1));
                    }
                });
                *c.borrow_mut() = matches!(r, Err(ExternalError::Cancelled));
                Err(HostFault::Cancel)
            },
        ),
    );
    run_main(&mut m, &p).expect("main");
    assert_eq!(
        m.coroutine_slots_live(),
        1,
        "the coroutine is parked in its host function"
    );
    assert!(!*cancelled.borrow());
    drop(m);
    assert!(
        *cancelled.borrow(),
        "the host function was resumed with a cancel"
    );
    assert_eq!(out.text(), "defer ran\n");
}
