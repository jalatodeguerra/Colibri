//! `#[colibri::module]` (phase 4 B2): a binding crate's registration function, run the way a
//! generated runner runs it (`__colibri_binding::register(&mut vm, "tools")`). Everything the
//! binding offers sits in the module `tools`, so scripts `import tools`.

use std::io::Write;
use std::sync::{Arc, Mutex};

use colibri::{Callback, Ctx, TypedError};
use colibri_runtime as colibri;

#[colibri::export(value)]
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Point {
    pub x: f32,
    pub y: f32,
}

#[colibri::export]
pub struct Counter {
    n: i64,
}

#[colibri::export]
impl Counter {
    pub fn new(start: i64) -> Counter {
        Counter { n: start }
    }

    pub fn get(&self) -> i64 {
        self.n
    }

    pub fn bump(&mut self, by: i64) -> i64 {
        self.n += by;
        self.n
    }

    pub fn explode() -> Counter {
        panic!("static went off")
    }

    pub fn fail(&self) -> i64 {
        panic!("method went off")
    }

    pub fn origin(&self, p: &Point) -> Point {
        Point {
            x: p.x + self.n as f32,
            y: p.y,
        }
    }
}

/// Its Rust `Drop` panics when the script lets go of it.
#[colibri::export]
pub struct Fragile;

#[colibri::export]
#[allow(clippy::new_without_default)]
impl Fragile {
    pub fn new() -> Fragile {
        Fragile
    }
}

impl Drop for Fragile {
    fn drop(&mut self) {
        panic!("drop went off");
    }
}

#[colibri::export]
pub fn double(n: i64) -> i64 {
    n * 2
}

#[colibri::export]
pub fn shout(text: &str) -> String {
    text.to_uppercase()
}

#[colibri::export]
pub fn halve(n: i64) -> Result<i64, String> {
    if n % 2 == 0 {
        Ok(n / 2)
    } else {
        Err(format!("{n} is odd"))
    }
}

#[colibri::export]
pub fn halve_typed(n: i64) -> Result<i64, TypedError> {
    if n % 2 == 0 {
        Ok(n / 2)
    } else {
        Err(TypedError::new(
            "tools",
            "Error",
            "Odd",
            format!("{n} is odd"),
        ))
    }
}

/// Calls the script's closure and does not expect it to fail.
#[colibri::export]
pub fn apply(cx: &mut Ctx, f: Callback<(i64,), i64>, n: i64) -> i64 {
    f.call(cx, (n,)).unwrap()
}

#[colibri::module]
fn tools(m: &mut colibri::Module<'_>) -> Result<(), colibri::Error> {
    m.register_module_enum("Error", &["Odd", "Negative"])?;
    m.add_class::<Point>()?;
    m.add_class::<Counter>()?;
    m.add_class::<Fragile>()?;
    m.add_fn(double::export)?;
    m.add_fn(shout::export)?;
    m.add_fn(halve::export)?;
    m.add_fn(halve_typed::export)?;
    m.add_fn(apply::export)?;
    Ok(())
}

const GOLDEN_CBI: &str = "\
// Generated by colibri-runtime; do not edit.
@interface(format = 1, module = \"tools\", hash = \"3568421adb1c9295\", caps = [])
@module enum Error { Odd, Negative }
struct Point { x: f32, y: f32 }
@host class Counter {}
impl Counter {
    fn new(start: int) -> Counter
    fn get(self) -> int
    fn bump(self, by: int) -> int
    fn explode() -> Counter
    fn fail(self) -> int
    fn origin(self, p: Point) -> Point
}
@host class Fragile {}
impl Fragile {
    fn new() -> Fragile
}
fn double(n: int) -> int
fn shout(text: str) -> str
fn halve(n: int) -> Result[int]
fn halve_typed(n: int) -> Result[int]
fn apply(f: fn(int) -> int, n: int) -> int
";

/// The registration a runner does, plus a shared stdout.
fn vm_with(source: &str) -> (colibri::Vm, colibri::SharedBuffer) {
    let out = colibri::SharedBuffer::new();
    let mut vm = colibri::Vm::builder().stdout(Box::new(out.clone())).build();
    __colibri_binding::register(&mut vm, "tools").unwrap();
    vm.load_source("main.colibri", source).unwrap();
    (vm, out)
}

fn panic_text(r: Result<(), colibri::Error>) -> String {
    match r.unwrap_err() {
        colibri::Error::Panic { message, stack, .. } => format!(
            "{message} [{}]",
            stack
                .iter()
                .map(|f| f.function.clone())
                .collect::<Vec<_>>()
                .join(", ")
        ),
        other => panic!("{other:?}"),
    }
}

#[test]
fn the_binding_knows_its_rust_name_and_registers_under_the_name_it_is_given() {
    assert_eq!(__colibri_binding::NAME, "tools");
    let out = colibri::SharedBuffer::new();
    let mut vm = colibri::Vm::builder().stdout(Box::new(out.clone())).build();
    __colibri_binding::register(&mut vm, "native").unwrap();
    vm.load_source(
        "main.colibri",
        "import native\nfn main() {\n    print(native.double(4))\n}\n",
    )
    .unwrap();
    vm.run_main().unwrap();
    assert_eq!(out.contents(), "8\n");
    // `tools` is the Rust name only: nothing is registered under it.
    assert!(!vm.module("tools").interface_text().contains("double"));
}

#[test]
fn the_interface_text_of_the_module_is_golden() {
    let (mut vm, _) = vm_with("fn main() {\n}\n");
    let text = vm.module("tools").interface_text();
    assert_eq!(text, GOLDEN_CBI, "\n{text}");
    // Nothing leaked into the root module.
    let root = vm.interface_text();
    assert!(!root.contains("double"), "{root}");
    assert!(!root.contains("Counter"), "{root}");
}

#[test]
fn a_script_uses_the_value_struct_the_class_and_the_functions_after_an_import() {
    let (mut vm, out) = vm_with(
        r#"import tools

fn main() {
    let c = tools.Counter.new(5)
    print(c.get())
    print(c.bump(3))
    print(c.bump(by: 2))
    print(c.origin(tools.Point { x: 1.0, y: 2.0 }))
    print(tools.double(21))
    print(tools.shout("hey"))
}
"#,
    );
    vm.run_main().unwrap();
    assert_eq!(
        out.contents(),
        "5\n8\n10\nPoint { x: 11.0, y: 2.0 }\n42\nHEY\n"
    );
}

#[test]
fn the_module_is_not_in_the_root_module() {
    let out = colibri::SharedBuffer::new();
    let mut vm = colibri::Vm::builder().stdout(Box::new(out)).build();
    __colibri_binding::register(&mut vm, "tools").unwrap();
    // Without the import the names do not exist.
    let err = vm
        .load_source("main.colibri", "fn main() {\n    print(double(2))\n}\n")
        .unwrap_err();
    assert!(err.to_string().contains("double"), "{err}");
}

#[test]
fn a_result_that_is_an_err_reaches_the_script_as_err_with_the_message() {
    let (mut vm, out) = vm_with(
        r#"import tools

fn main() {
    match tools.halve(8) {
        ok(v) => print("half {v}")
        err(e) => print("failed {e}")
    }
    match tools.halve(7) {
        ok(v) => print("half {v}")
        err(e) => print("failed {e}")
    }
}
"#,
    );
    vm.run_main().unwrap();
    assert_eq!(out.contents(), "half 4\nfailed 7 is odd\n");
}

#[test]
fn a_typed_error_keeps_its_variant_through_the_module_enum() {
    let (mut vm, out) = vm_with(
        r#"import tools

fn main() {
    match tools.halve_typed(3) {
        ok(v) => print("half {v}")
        err(e) => {
            print("failed {e}")
            print(e.is[tools.Error]())
            print(e.as[tools.Error]())
        }
    }
}
"#,
    );
    vm.run_main().unwrap();
    assert_eq!(out.contents(), "failed 3 is odd\ntrue\nsome(Odd)\n");
}

#[test]
fn a_panic_in_a_static_function_names_it_and_the_vm_goes_on() {
    let (mut vm, out) = vm_with(
        "import tools\nfn main() {\n    let c = tools.Counter.explode()\n}\nfn after() -> int => tools.double(4)\n",
    );
    let text = panic_text(vm.run_main());
    assert!(
        text.contains("host function `Counter.explode` panicked: static went off"),
        "{text}"
    );
    let after = vm.get_fn::<(), i64>("after").unwrap();
    assert_eq!(after.call(&mut vm, ()).unwrap(), 8);
    assert_eq!(out.contents(), "");
}

#[test]
fn a_panic_in_a_method_names_it_and_the_object_is_still_usable() {
    let (mut vm, _) = vm_with(
        "import tools\nfn crash(c: tools.Counter) -> int => c.fail()\nfn read(c: tools.Counter) -> int => c.get()\n",
    );
    let c = vm.insert(Counter::new(11));
    let crash = vm
        .get_fn::<(colibri::Handle<Counter>,), i64>("crash")
        .unwrap();
    let err = crash.call(&mut vm, (c,)).unwrap_err().to_string();
    assert!(
        err.contains("host function `Counter.fail` panicked: method went off"),
        "{err}"
    );
    // The borrow of the object was given back by the unwind.
    let read = vm
        .get_fn::<(colibri::Handle<Counter>,), i64>("read")
        .unwrap();
    assert_eq!(read.call(&mut vm, (c,)).unwrap(), 11);
}

#[test]
fn a_panic_in_drop_names_the_class_and_the_vm_goes_on() {
    let (mut vm, _) = vm_with(
        "import tools\nfn scope() {\n    let f = tools.Fragile.new()\n}\nfn after() -> int => tools.double(5)\n",
    );
    let scope = vm.get_fn::<(), ()>("scope").unwrap();
    let err = scope.call(&mut vm, ()).unwrap_err().to_string();
    assert!(
        err.contains("dropping the host object `Fragile` panicked: drop went off"),
        "{err}"
    );
    assert_eq!(vm.host_object_count(), 0);
    let after = vm.get_fn::<(), i64>("after").unwrap();
    assert_eq!(after.call(&mut vm, ()).unwrap(), 10);
}

#[test]
fn a_failing_callback_is_a_panic_that_names_the_function_that_called_it() {
    let (mut vm, out) = vm_with(
        r#"import tools

fn main() {
    print(tools.apply(fn(n) => n + 1, 4))
    print(tools.apply(fn(n) => 10 / n, 0))
}
fn after() -> int => tools.apply(fn(n) => n * 3, 3)
"#,
    );
    let text = panic_text(vm.run_main());
    assert!(text.contains("host function `apply` panicked"), "{text}");
    assert!(text.contains("division by zero"), "{text}");
    assert_eq!(out.contents(), "5\n");
    let after = vm.get_fn::<(), i64>("after").unwrap();
    assert_eq!(after.call(&mut vm, ()).unwrap(), 9);
}

#[test]
fn registering_a_binding_twice_is_an_error() {
    let mut vm = colibri::Vm::new();
    __colibri_binding::register(&mut vm, "tools").unwrap();
    let err = __colibri_binding::register(&mut vm, "tools").unwrap_err();
    assert!(
        err.to_string()
            .contains("the module `tools` is already registered"),
        "{err}"
    );
    // The first registration is untouched.
    assert!(vm.module("tools").interface_text().contains("fn double"));
    // Another name does not help: a class belongs to the module that described it first.
    let err = __colibri_binding::register(&mut vm, "tools2").unwrap_err();
    assert!(
        err.to_string().contains("belongs to the module `tools`"),
        "{err}"
    );
    // The reserved and unusable names are refused too.
    for bad in ["std", "std.fs", "has space", "host"] {
        assert!(
            __colibri_binding::register(&mut vm, bad).is_err(),
            "`{bad}` was accepted"
        );
    }
}

/// A second binding in a module of its own: the generated `__colibri_binding` sits next to the
/// function, so a crate's binding goes at its root and this one is reached by path.
mod classes_only {
    use super::*;

    #[colibri::module]
    pub fn only_classes(m: &mut colibri::Module<'_>) -> Result<(), colibri::Error> {
        m.add_class::<Point>()
    }
}

#[test]
fn a_binding_that_registers_only_classes_cannot_register_twice_either() {
    assert_eq!(classes_only::__colibri_binding::NAME, "only_classes");
    let mut vm = colibri::Vm::new();
    classes_only::__colibri_binding::register(&mut vm, "only").unwrap();
    let err = classes_only::__colibri_binding::register(&mut vm, "only").unwrap_err();
    assert!(err.to_string().contains("already registered"), "{err}");
}

/// A sink that worker threads can write to.
#[derive(Clone, Default)]
struct Out(Arc<Mutex<Vec<u8>>>);

impl Write for Out {
    fn write(&mut self, buf: &[u8]) -> std::io::Result<usize> {
        self.0.lock().unwrap().extend_from_slice(buf);
        Ok(buf.len())
    }
    fn flush(&mut self) -> std::io::Result<()> {
        Ok(())
    }
}

#[test]
fn a_thread_task_calls_a_binding_function_registered_by_the_worker_setup() {
    let out = Out::default();
    let mut vm = colibri::Vm::builder()
        .worker_threads(1)
        .stdout_shared(Box::new(out.clone()))
        .worker_setup(|vm| __colibri_binding::register(vm, "tools").unwrap())
        .build();
    __colibri_binding::register(&mut vm, "tools").unwrap();
    vm.load_source(
        "main.colibri",
        r#"import tools

fn main() -> Result[()] {
    let t = task.run(fn() => tools.double(21))
    print("task gave {t.join()?}")
    let bad = task.run(fn() => tools.Counter.explode().get())
    match bad.join() {
        ok(v) => print("no failure {v}")
        err(e) => print("failed")
    }
    return ok(())
}
"#,
    )
    .unwrap();
    vm.run_main().unwrap();
    vm.run_event_loop().unwrap();
    let text = String::from_utf8_lossy(&out.0.lock().unwrap()).into_owned();
    assert_eq!(text, "task gave 42\nfailed\n");
}
